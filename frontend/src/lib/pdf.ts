export function downloadReportPdf(data: PdfReportData, options: PdfOptions = {}): void {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  let y = CONTENT_TOP;

  // Page 1: what happened, is anything wrong, what policy was used.
  y = summaryCard(doc, y, data);
  y += 8;
  const issues = [...headerIssues(data.findings), ...cspIssues(data.csp_finding)];
  y = executiveSummary(doc, y + 12, data);
  y = severityBreakdown(doc, y + 18, issues);
  y = keyFindings(doc, y + 8, issues, Boolean(data.csp_finding));
  y = policySection(doc, y, buildPolicyView(data, options.policy), options.policyNote);

  // Evidence: each header against its expected value.
  if (data.findings.length > 0) {
    y = beginSection(
      doc,
      y,
      "Header Findings",
      "Status shows whether the response complies with the configured policy - not whether the header is modern best practice.",
      { minSpace: 200 }
    );
    autoTable(doc, {
      ...TABLE_STYLE,
      startY: y,
      head: [["Header", "Status", "Severity", "Score", "Policy Expected", "Actual Value"]],
      body: data.findings.map((f) => {
        // Keep the raw value; show what it normalized to when that is why it matched.
        const normalized = f.checks.map((c) => c.evidence).find((e) => e);
        return [
          f.header,
          f.status,
          f.severity,
          `${f.score_earned}/${f.score_possible}`,
          describeExpected(f.header, f.policy_expected),
          `${f.actual_value ?? "(missing)"}${normalized ? `\n(${normalized})` : ""}`,
        ];
      }),
      columnStyles: { 0: { fontStyle: "bold" }, 4: { cellWidth: 115 }, 5: { cellWidth: 115 } },
      didParseCell: statusColorHook(1),
    });
    y = finalY(doc) + 22;
  }

  y = recommendations(doc, y, data);

  if (data.csp_finding && data.csp_finding.policy_checks.length + data.csp_finding.security_checks.length > 0) {
    y = cspSection(doc, y, data.csp_finding);
  }

  decoratePages(doc, data);

  const slug = (data.target ?? "scan").replace(/[^a-z0-9]+/gi, "-").toLowerCase().slice(0, 40);
  const suffix = data.scan_number ? `scan-${data.scan_number}` : "result";
  doc.save(`hedr-${slug}-${suffix}.pdf`);
}
