// ---- expected-value wording ----------------------------------------------------

/** Plain-language form of a policy's expected value. Cache-Control's mini-syntax
 * (`a, b` = exact set, trailing `+` = extras allowed, `!x` = prohibited) is
 * spelled out so a reader never has to guess whether extra directives fail. */
function describeExpected(header: string, value: string | null | undefined): string {
  const text = (value ?? "").trim();
  if (!text) return "Present (any value)";
  if (header.trim().toLowerCase() !== "cache-control") return text;
  const tokens = text.split(",").map((t) => t.trim()).filter(Boolean);
  const extrasAllowed = tokens.includes("+");
  const prohibited = tokens.filter((t) => t.startsWith("!")).map((t) => t.slice(1));
  const required = tokens.filter((t) => t !== "+" && !t.startsWith("!"));
  const parts = [];
  if (required.length) parts.push(`Required: ${required.join(", ")}`);
  if (prohibited.length) parts.push(`Prohibited: ${prohibited.join(", ")}`);
  parts.push(extrasAllowed ? "Extra directives: allowed" : "Extra directives: not allowed (exact set)");
  return parts.join("\n");
}

// ---- findings model --------------------------------------------------------------

const SEVERITY_ORDER: SeverityLevel[] = ["critical", "high", "medium", "low", "info"];
const SEVERITY_COLOR: Record<SeverityLevel, RGB> = {
  critical: [150, 20, 20],
  high: [200, 50, 50],
  medium: [200, 130, 20],
  low: [70, 120, 180],
  info: [120, 120, 128],
};
const POLICY_TAG: RGB = ACCENT;
const BEST_PRACTICE_TAG: RGB = [90, 100, 200];

type IssueSource = "header" | "csp-policy" | "csp-best-practice";

/** Something the reader may need to act on: a failed check or a warning.
 * PASS results and INFO notes are never findings. */
interface Issue {
  label: string;
  message: string;
  severity: SeverityLevel;
  status: "FAIL" | "WARNING";
  source: IssueSource;
}

function cspIssues(csp: CSPFinding | null): Issue[] {
  if (!csp) return [];
  const toIssue = (c: CheckResult, source: IssueSource): Issue | null =>
    c.status === "FAIL" || c.status === "WARNING"
      ? { label: c.id ?? "CSP", message: c.description, severity: c.severity ?? "info", status: c.status, source }
      : null;
  return [
    ...csp.policy_checks.map((c) => toIssue(c, "csp-policy")),
    ...csp.security_checks.map((c) => toIssue(c, "csp-best-practice")),
  ].filter((i): i is Issue => i !== null);
}

function headerIssues(findings: HeaderFinding[]): Issue[] {
  const issues: Issue[] = [];
  for (const f of findings) {
    if (f.status === "FAIL") {
      issues.push({
        label: f.header,
        message: f.issue ?? "The value does not comply with the configured policy.",
        severity: f.severity,
        status: "FAIL",
        source: "header",
      });
    }
    for (const a of f.advisories ?? []) {
      if (a.status === "WARNING") {
        issues.push({ label: f.header, message: `${a.title}. ${a.message}`, severity: a.severity, status: "WARNING", source: "header" });
      }
    }
  }
  return issues;
}

function rankIssues(issues: Issue[]): Issue[] {
  return [...issues].sort(
    (a, b) =>
      SEVERITY_ORDER.indexOf(a.severity) - SEVERITY_ORDER.indexOf(b.severity) ||
      (a.status === b.status ? 0 : a.status === "FAIL" ? -1 : 1)
  );
}

function assessment(grade: string): string {
  switch (grade) {
    case "A":
      return "Excellent - the header configuration meets the policy.";
    case "B":
      return "Good - most checks pass, with a few gaps to close.";
    case "C":
      return "Fair - several checks failed against the policy.";
    case "D":
      return "Weak - many checks failed against the policy.";
    default:
      return "Needs attention - most checks failed against the policy.";
  }
}

function plural(n: number, one: string, many: string): string {
  return n === 1 ? one : many;
}

function smallHeading(doc: jsPDF, x: number, y: number, text: string): void {
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8.5);
  doc.setTextColor(...MUTED);
  doc.text(text.toUpperCase(), x, y);
}

function severityTag(doc: jsPDF, x: number, y: number, text: string, color: RGB): number {
  doc.setFont("helvetica", "bold");
  doc.setFontSize(7);
  const w = doc.getTextWidth(text) + 10;
  doc.setFillColor(...color);
  doc.roundedRect(x, y, w, 13, 3, 3, "F");
  doc.setTextColor(255, 255, 255);
  doc.text(text, x + 5, y + 9.3);
  return w;
}

// ---- page 1: executive summary, severity, key findings ---------------------------------

function executiveSummary(doc: jsPDF, y: number, data: PdfReportData): number {
  const headersPassed = data.findings.filter((f) => f.status === "PASS").length;
  const headersFailed = data.findings.filter((f) => f.status === "FAIL").length;
  const total = data.findings.length;
  const csp = data.csp_finding;
  const gap = 10;
  const tileW = (CONTENT_W - gap * 2) / 3;
  const at = (i: number) => MARGIN_X + i * (tileW + gap);

  y = sectionHeading(doc, y, "Executive Summary");
  statTile(doc, at(0), y, tileW, `Header ${plural(headersPassed, "rule", "rules")} passed`, total ? `${headersPassed} / ${total}` : "n/a", total ? PASS : MUTED);
  statTile(doc, at(1), y, tileW, `Header ${plural(headersFailed, "rule", "rules")} failed`, total ? `${headersFailed} / ${total}` : "n/a", headersFailed > 0 ? FAIL : MUTED);
  statTile(doc, at(2), y, tileW, `Header ${plural(total, "rule", "rules")} checked`, String(total), INK);
  y += 46 + gap;
  if (csp) {
    const pctColor = (done: number, of: number): RGB => (of === 0 ? MUTED : done === of ? PASS : done / of >= 0.6 ? WARN : FAIL);
    statTile(doc, at(0), y, tileW, "CSP policy checks passed", `${csp.policy_checks_passed} / ${csp.policy_checks_total}`, pctColor(csp.policy_checks_passed, csp.policy_checks_total));
    statTile(doc, at(1), y, tileW, "CSP best-practice checks passed", `${csp.best_practice_passed} / ${csp.best_practice_total}`, pctColor(csp.best_practice_passed, csp.best_practice_total));
    statTile(doc, at(2), y, tileW, "Overall CSP score", String(csp.overall_score), INK);
    y += 46 + gap;
  } else {
    // Same three tiles, so the layout doesn't change when CSP isn't evaluated.
    statTile(doc, at(0), y, tileW, "CSP policy checks passed", "N/A", MUTED);
    statTile(doc, at(1), y, tileW, "CSP best-practice checks passed", "N/A", MUTED);
    statTile(doc, at(2), y, tileW, "Overall CSP score", "N/A", MUTED);
    y += 46 + gap;
  }
  return y;
}

/** Small section heading used inside page 1 (lighter than a full section). */
function sectionHeading(doc: jsPDF, y: number, title: string): number {
  doc.setFillColor(...ACCENT);
  doc.roundedRect(MARGIN_X, y - 11, 3.5, 15, 1.5, 1.5, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.setTextColor(...INK);
  doc.text(title, MARGIN_X + 11, y);
  return y + 16;
}

function severityBreakdown(doc: jsPDF, y: number, issues: Issue[]): number {
  y = sectionHeading(doc, y, "Findings by Severity");
  const counts = SEVERITY_ORDER.map((sev) => issues.filter((i) => i.severity === sev).length);
  const max = Math.max(1, ...counts);
  const labelW = 60;
  const barX = MARGIN_X + labelW;
  const barW = CONTENT_W - labelW - 40;
  SEVERITY_ORDER.forEach((sev, i) => {
    const ry = y + i * 18;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...INK);
    doc.text(sev[0].toUpperCase() + sev.slice(1), MARGIN_X, ry + 8);
    doc.setFillColor(...LINE);
    doc.roundedRect(barX, ry, barW, 10, 5, 5, "F");
    if (counts[i] > 0) {
      doc.setFillColor(...SEVERITY_COLOR[sev]);
      doc.roundedRect(barX, ry, Math.max(10, (barW * counts[i]) / max), 10, 5, 5, "F");
    }
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...(counts[i] > 0 ? INK : MUTED));
    doc.text(String(counts[i]), PAGE_W - MARGIN_X, ry + 8, { align: "right" });
  });
  y += SEVERITY_ORDER.length * 18;
  return y + 20;
}

const KEY_FINDINGS_SHOWN = 5;

function keyFindings(doc: jsPDF, y: number, issues: Issue[], cspEvaluated: boolean): number {
  y = sectionHeading(doc, y, "Key Findings");
  if (issues.length === 0) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(...PASS);
    doc.text("No issues found.", MARGIN_X, y + 6);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(...MUTED);
    doc.text(cspEvaluated ? "Every header rule and CSP check passed." : "Every header rule passed.", MARGIN_X, y + 19);
    return y + 34;
  }
  const ranked = rankIssues(issues);
  const shown = ranked.slice(0, KEY_FINDINGS_SHOWN);
  for (const item of shown) {
    y = ensureSpace(doc, y, 34);
    const tagW = severityTag(doc, MARGIN_X, y, item.severity.toUpperCase(), SEVERITY_COLOR[item.severity]);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(...INK);
    const textX = MARGIN_X + tagW + 8;
    const lines = (doc.splitTextToSize(`${item.label} - ${item.message}`, CONTENT_W - tagW - 8) as string[]).slice(0, 2);
    doc.setFont("helvetica", "normal");
    doc.text(lines, textX, y + 10);
    y += Math.max(20, lines.length * 11 + 9);
  }
  if (ranked.length > shown.length) {
    doc.setFont("helvetica", "italic");
    doc.setFontSize(8);
    doc.setTextColor(...MUTED);
    doc.text(`+ ${ranked.length - shown.length} more ${plural(ranked.length - shown.length, "finding", "findings")} detailed later in this report`, MARGIN_X, y + 6);
    y += 16;
  }
  return y + 6;
}

// ---- recommendations ------------------------------------------------------------------

interface RecField {
  label: string;
  lines: string[];
}

function recommendationCard(doc: jsPDF, y: number, title: string, tagText: string, tagColor: RGB, fields: RecField[]): number {
  const labelW = 70;
  const lineH = 10.5;
  const bodyH = fields.reduce((sum, f) => sum + f.lines.length * lineH + 4, 0);
  const h = 30 + bodyH;
  y = ensureSpace(doc, y, h + 8);
  doc.setFillColor(...CARD);
  doc.setDrawColor(...LINE);
  doc.setLineWidth(0.5);
  doc.roundedRect(MARGIN_X, y, CONTENT_W, h, 5, 5, "FD");
  doc.setFillColor(...tagColor);
  doc.roundedRect(MARGIN_X, y, 3.5, h, 1.5, 1.5, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(...INK);
  doc.text(title, MARGIN_X + 14, y + 17);
  severityTag(doc, MARGIN_X + 14 + doc.getTextWidth(title) + 8, y + 7, tagText, tagColor);
  let fy = y + 32;
  for (const field of fields) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(7.5);
    doc.setTextColor(...MUTED);
    doc.text(field.label.toUpperCase(), MARGIN_X + 14, fy);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(...INK);
    doc.text(field.lines, MARGIN_X + 14 + labelW, fy);
    fy += field.lines.length * lineH + 4;
  }
  return y + h + 8;
}

function wrap(doc: jsPDF, text: string, width: number): string[] {
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  return doc.splitTextToSize(text, width) as string[];
}

function recommendations(doc: jsPDF, y: number, data: PdfReportData): number {
  const textW = CONTENT_W - 28 - 70;
  const failing = data.findings.filter((f) => f.status !== "PASS" && (f.issue || f.recommendation));
  const notes = data.findings.flatMap((f) => (f.advisories ?? []).map((a) => ({ header: f.header, advisory: a })));
  if (failing.length === 0 && notes.length === 0) return y;

  y = beginSection(doc, y, "Recommendations", "What to change, and why. Expected and actual values are shown side by side.", { minSpace: 170 });
  for (const f of failing) {
    y = recommendationCard(doc, y, f.header, f.severity.toUpperCase(), SEVERITY_COLOR[f.severity], [
      { label: "Issue", lines: wrap(doc, f.issue ?? "The value does not comply with the configured policy.", textW) },
      { label: "Expected", lines: wrap(doc, describeExpected(f.header, f.policy_expected).replace(/\n/g, "; "), textW) },
      { label: "Actual", lines: wrap(doc, f.actual_value ?? "(header not present)", textW) },
      { label: "Remediation", lines: wrap(doc, f.recommendation ?? "Update the header so its value complies with the configured policy.", textW) },
    ]);
  }
  for (const { header, advisory } of notes) {
    y = recommendationCard(doc, y, header, advisory.status, STATUS_COLOR[advisory.status] ?? MUTED, [
      { label: "Note", lines: wrap(doc, `${advisory.title}. ${advisory.message}`, textW) },
      ...(advisory.recommendation ? [{ label: "Action", lines: wrap(doc, advisory.recommendation, textW) }] : []),
    ]);
  }
  return y;
}

// ---- Content-Security-Policy ------------------------------------------------------------

const RISKY_SOURCES = ["'unsafe-inline'", "'unsafe-eval'", "*", "http:"];
const CAUTION_SOURCES = ["data:", "blob:"];

function cspReceived(doc: jsPDF, y: number, csp: CSPFinding): number {
  smallHeading(doc, MARGIN_X, y, "CSP received");
  y += 10;
  if (!csp.present || !csp.actual_value) {
    doc.setFont("helvetica", "italic");
    doc.setFontSize(9);
    doc.setTextColor(...MUTED);
    doc.text("The response did not include a Content-Security-Policy header.", MARGIN_X, y + 8);
    return y + 26;
  }
  // One row per directive: its name, then its sources.
  const rows = csp.actual_value
    .split(";")
    .map((d) => d.trim())
    .filter(Boolean)
    .map((d) => {
      const [name, ...sources] = d.split(/\s+/);
      return [name, sources.length ? sources.join("   ") : "(no sources)"];
    });
  y = ensureSpace(doc, y, 60);
  autoTable(doc, {
    ...TABLE_STYLE,
    startY: y,
    head: [["Directive", "Sources"]],
    body: rows,
    styles: { ...TABLE_STYLE.styles, font: "courier", fontSize: 8, cellPadding: 5 },
    headStyles: { ...TABLE_STYLE.headStyles, font: "helvetica" },
    columnStyles: { 0: { cellWidth: 110, fontStyle: "bold", textColor: ACCENT } },
    didParseCell: (hook) => {
      if (hook.section !== "body" || hook.column.index !== 1) return;
      const tokens = String(hook.cell.raw).split(/\s+/).filter(Boolean);
      if (String(hook.cell.raw) === "(no sources)") hook.cell.styles.textColor = MUTED;
      else if (tokens.some((t) => RISKY_SOURCES.includes(t))) hook.cell.styles.textColor = FAIL;
      else if (tokens.some((t) => CAUTION_SOURCES.includes(t))) hook.cell.styles.textColor = WARN;
    },
  });
  y = finalY(doc) + 6;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7.5);
  doc.setTextColor(...MUTED);
  doc.text("Red: contains a risky source ('unsafe-inline', 'unsafe-eval', *, http:).  Amber: contains data: or blob:.", MARGIN_X, y + 6);
  return y + 30;
}

function cspFindings(doc: jsPDF, y: number, csp: CSPFinding): number {
  const issues = rankIssues(cspIssues(csp));
  const policyCount = issues.filter((i) => i.source === "csp-policy").length;
  const bpCount = issues.filter((i) => i.source === "csp-best-practice").length;
  y = ensureSpace(doc, y, 60);
  smallHeading(doc, MARGIN_X, y, "CSP findings");
  y += 12;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(...INK);
  doc.text(`${policyCount} policy ${plural(policyCount, "issue", "issues")}   ·   ${bpCount} best-practice ${plural(bpCount, "issue", "issues")}`, MARGIN_X, y + 6);
  y += 20;
  if (issues.length === 0) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...PASS);
    doc.text("No CSP issues found.", MARGIN_X, y + 6);
    return y + 22;
  }
  const textW = CONTENT_W - 130;
  for (const item of issues) {
    const lines = wrap(doc, `${item.label}  ${item.message}`, textW);
    y = ensureSpace(doc, y, lines.length * 11 + 12);
    severityTag(doc, MARGIN_X, y, item.severity.toUpperCase(), SEVERITY_COLOR[item.severity]);
    severityTag(doc, MARGIN_X + 58, y, item.source === "csp-policy" ? "POLICY" : "BEST PRACTICE", item.source === "csp-policy" ? POLICY_TAG : BEST_PRACTICE_TAG);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(...INK);
    doc.text(lines, MARGIN_X + 140, y + 10);
    y += Math.max(20, lines.length * 11 + 8);
  }
  return y + 8;
}

/** Checks grouped by directive, with a group row per directive, so the many
 * repeated per-directive checks (wildcard, external, http, data, blob...) read
 * as one block each instead of one long undifferentiated table. */
function cspDetailRows(csp: CSPFinding): unknown[][] {
  const all: { check: CheckResult; category: string }[] = [
    ...csp.policy_checks.map((check) => ({ check, category: "Policy" })),
    ...csp.security_checks.map((check) => ({ check, category: "Best practice" })),
  ];
  const groups = new Map<string, typeof all>();
  for (const item of all) {
    const key = item.check.directive ?? "General";
    groups.set(key, [...(groups.get(key) ?? []), item]);
  }
  const rows: unknown[][] = [];
  for (const [directive, items] of groups) {
    rows.push([{ content: directive, colSpan: 7, styles: { fillColor: ACCENT_SOFT, fontStyle: "bold", textColor: INK } }]);
    for (const { check, category } of items) {
      rows.push([
        check.id ?? "-",
        category,
        check.description,
        check.severity ?? "-",
        check.status,
        check.expected ?? "-",
        check.actual ?? "-",
      ]);
    }
  }
  return rows;
}

function cspSection(doc: jsPDF, y: number, csp: CSPFinding): number {
  y = beginSection(doc, y, "Content-Security-Policy Analysis", "Where the CSP stands first; the detailed evidence follows.", { minSpace: 260 });
  const gap = 10;
  const tileW = (CONTENT_W - gap * 2) / 3;
  const at = (i: number) => MARGIN_X + i * (tileW + gap);
  const tone = (done: number, of: number): RGB => (of === 0 ? MUTED : done === of ? PASS : done / of >= 0.6 ? WARN : FAIL);
  statTile(doc, at(0), y, tileW, "Overall CSP score", `${csp.overall_score} / 100`, INK);
  statTile(doc, at(1), y, tileW, "Policy compliance", `${csp.policy_checks_passed} / ${csp.policy_checks_total}`, tone(csp.policy_checks_passed, csp.policy_checks_total));
  statTile(doc, at(2), y, tileW, "Best practice", `${csp.best_practice_passed} / ${csp.best_practice_total}`, tone(csp.best_practice_passed, csp.best_practice_total));
  y += 46 + 20;
  y = cspReceived(doc, y, csp);
  y = cspFindings(doc, y, csp);

  y = beginSection(
    doc,
    y,
    "Detailed CSP Analysis",
    "Policy checks are the rules you configured. Best-practice checks are extra recommendations from Hedr - a policy check can pass while a best-practice check fails.",
    { newPage: true }
  );
  autoTable(doc, {
    ...TABLE_STYLE,
    startY: y,
    head: [["ID", "Category", "Check", "Severity", "Status", "Expected", "Actual"]],
    body: cspDetailRows(csp) as never,
    columnStyles: { 0: { fontStyle: "bold", cellWidth: 46 }, 1: { cellWidth: 66 } },
    didParseCell: (hook) => {
      if (hook.section !== "body") return;
      const raw = String(hook.cell.raw);
      if (hook.column.index === 4 && STATUS_COLOR[raw]) {
        hook.cell.styles.textColor = STATUS_COLOR[raw];
        hook.cell.styles.fontStyle = "bold";
      }
      if (hook.column.index === 1) {
        hook.cell.styles.textColor = raw === "Policy" ? POLICY_TAG : BEST_PRACTICE_TAG;
        hook.cell.styles.fontStyle = "bold";
      }
    },
  });
  return finalY(doc) + 16;
}

